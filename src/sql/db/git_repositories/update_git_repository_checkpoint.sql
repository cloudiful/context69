-- The checkpoint advances only for a repository owned by $1; the join also
-- re-reads the authoritative group row and active generation pointer.
--
-- $1 group_id, $2 repository_key, $3 target_commit_sha, $4 indexed_commit_sha,
-- $5 index_status, $6 indexed_pipeline_version, $7 indexed_config_fingerprint,
-- $8 last_skip_summary. The identity and skip summary are only replaced when
-- this update records a completed snapshot ($6/$7/$8 not null).
WITH updated AS (
    UPDATE context69.git_repository_sources
    SET target_commit_sha = COALESCE($3, target_commit_sha),
        indexed_commit_sha = COALESCE($4, indexed_commit_sha),
        index_status = $5,
        indexed_pipeline_version = COALESCE($6, indexed_pipeline_version),
        indexed_config_fingerprint = COALESCE($7, indexed_config_fingerprint),
        last_skip_summary = COALESCE($8, last_skip_summary),
        last_error_code = CASE WHEN $5 = 'ready' THEN NULL ELSE last_error_code END,
        checkpoint_updated_at = now(),
        last_indexed_at = CASE WHEN $4 IS NULL THEN last_indexed_at ELSE now() END,
        updated_at = now()
    WHERE group_id = $1
      AND repository_key = $2
    RETURNING
        group_id,
        repository_key,
        connection_key,
        provider_kind,
        canonical_url,
        repository_owner,
        repository_name,
        default_branch,
        target_ref,
        target_commit_sha,
        pinned_commit_sha,
        indexed_commit_sha,
        index_profile,
        include_patterns,
        exclude_patterns,
        interval_seconds,
        webhook_enabled,
        enabled,
        retention_count,
        created_by_user_id,
        config_revision,
        refresh_dirty,
        refresh_requested_at,
        last_refresh_attempt_at,
        force_rebuild_requested_at,
        deletion_requested_at,
        last_skip_summary,
        indexed_pipeline_version,
        indexed_config_fingerprint,
        index_status,
        last_error_code,
        last_indexed_at,
        checkpoint_updated_at,
        created_at,
        updated_at
)
SELECT
    updated.group_id,
    updated.repository_key,
    updated.connection_key,
    updated.provider_kind,
    updated.canonical_url,
    updated.repository_owner,
    updated.repository_name,
    updated.default_branch,
    updated.target_ref,
    updated.target_commit_sha,
    updated.pinned_commit_sha,
    updated.indexed_commit_sha,
    updated.index_profile,
    updated.include_patterns,
    updated.exclude_patterns,
    updated.interval_seconds,
    updated.webhook_enabled,
    updated.enabled,
    updated.retention_count,
    updated.created_by_user_id,
    updated.config_revision,
    updated.refresh_dirty,
    updated.refresh_requested_at,
    updated.last_refresh_attempt_at,
    updated.force_rebuild_requested_at,
    updated.deletion_requested_at,
    updated.last_skip_summary,
    updated.indexed_pipeline_version,
    updated.indexed_config_fingerprint,
    updated.index_status,
    updated.last_error_code,
    updated.last_indexed_at,
    updated.checkpoint_updated_at,
    updated.created_at,
    updated.updated_at,
    g.group_key,
    g.full_path AS group_path,
    g.visibility AS group_visibility,
    ag.generation_key AS "active_generation_key?"
FROM updated
JOIN context69.groups g ON g.id = updated.group_id
LEFT JOIN context69.git_repository_active_generations ag
    ON ag.repository_key = updated.repository_key
